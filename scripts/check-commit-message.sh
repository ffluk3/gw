#!/usr/bin/env bash
# Validate commit messages against the Conventional Commits format.
#
# This is the single source of truth for the rule. The commit-msg hook and CI
# both call it, so a message that passes locally passes in CI.
#
#   check-commit-message.sh --file .git/COMMIT_EDITMSG   # one message file
#   check-commit-message.sh --rev HEAD                   # one commit
#   check-commit-message.sh --range origin/main..HEAD    # every commit in range
#
# Exit 0 when every message is valid, 1 otherwise.
set -euo pipefail

# Commit types release-plz understands. Anything else is still a valid
# Conventional Commit, but it does not drive a version bump.
TYPES='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'

# commitlint's default. Long subjects are hard to read in `git log --oneline`.
HEADER_MAX=100

usage() {
  sed -n '2,11p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

die() {
  printf 'commit message: %s\n' "$*" >&2
  exit 1
}

# Remove what git adds around the message: comment lines and everything after
# the scissors line that `git commit --verbose` inserts.
strip_comments() {
  sed -e '/^# ------------------------ >8 ------------------------$/,$d' \
      -e '/^#/d' "$1"
}

# Print the header (first non-empty line) of a message on stdin.
header_of() {
  awk 'NF { print; exit }'
}

# Check one message. Origin is used in the error text.
validate_message() {
  local origin=$1
  local message header

  message=$(header_of)

  if [[ -z $message ]]; then
    die "$origin: empty commit message"
  fi

  header=$message

  # Merge commits are generated by git and cannot follow the format. Fixup
  # commits are temporary and are squashed before they land.
  case $header in
    "Merge "*|"Revert \"") return 0 ;;
    fixup!\ *|squash!\ *|amend!\ *) return 0 ;;
  esac

  if (( ${#header} > HEADER_MAX )); then
    die "$origin: header is ${#header} characters, limit is $HEADER_MAX"$'\n'"  $header"
  fi

  # type(scope)?!?: description
  local pattern="^($TYPES)(\([a-z0-9][a-z0-9._/-]*\))?(!)?: [^ ]"
  if [[ ! $header =~ $pattern ]]; then
    cat >&2 <<EOF
commit message: $origin: header is not a Conventional Commit

  $header

Expected:

  <type>(<scope>)?!: <description>

  type: one of feat, fix, docs, style, refactor, perf, test, build, ci,
        chore, revert
  scope: optional, lower-case, e.g. (clean) or (git)
  !:     optional, marks a breaking change
  description: short summary, no leading space

Examples:

  feat(clean): skip worktrees with uncommitted changes
  fix: resolve the repos root from the layout
  refactor!: drop the legacy shell implementation

Commit types that change the version:
  feat  -> minor
  fix   -> patch
  any type with ! or a BREAKING CHANGE footer -> major
EOF
    exit 1
  fi

  return 0
}

validate_file() {
  local path=$1
  [[ -f $path ]] || die "$path: no such file"
  strip_comments "$path" | validate_message "$path"
}

validate_rev() {
  local rev=$1
  [[ $(git cat-file -t "$rev^{commit}" 2>/dev/null || true) == commit ]] \
    || die "$rev: not a commit"
  git log -1 --format=%B "$rev" | validate_message "$rev"
}

validate_range() {
  local range=$1
  local base=${range%%..*}
  local head=${range##*..}
  local sha failed=0

  # A branch's first push has no base commit. Validate what was pushed.
  if [[ -z $base ]] || ! git rev-parse --verify --quiet "$base^{commit}" >/dev/null; then
    printf 'commit message: no base commit in %s, checking only %s\n' \
      "$range" "$head" >&2
    validate_rev "$head"
    return
  fi

  while IFS= read -r sha; do
    [[ -n $sha ]] || continue
    if ! git log -1 --format=%B "$sha" \
        | validate_message "$(git log -1 --format='%h %s' "$sha")"; then
      failed=1
    fi
  done < <(git log --no-merges --format=%H "$range")

  return $failed
}

mode=
arg=
while (($#)); do
  case $1 in
    --file|--rev|--range)
      mode=$1
      arg=${2-}
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "unknown argument: $1"
      ;;
  esac
done

if [[ -z $mode || -z $arg ]]; then
  usage >&2
  exit 2
fi

# Keep git from paginating when the message contains something odd.
export GIT_PAGER=cat

case $mode in
  --file) validate_file "$arg" ;;
  --rev) validate_rev "$arg" ;;
  --range) validate_range "$arg" ;;
esac
